import { Card } from "@/components/ui/card";
import { Progress } from "@/components/ui/progress";
import { Badge } from "@/components/ui/badge";
import { Scale, TrendingUp } from "lucide-react";
import { calculateInnocenceScore, getScoreCategory } from "@/lib/innocence-score";

interface InnocenceScoreCardProps {
  analysis: any;
  legalMemo?: any;
  compact?: boolean;
}

const InnocenceScoreCard = ({ analysis, legalMemo, compact = false }: InnocenceScoreCardProps) => {
  const score = calculateInnocenceScore({
    innocenceClaims: analysis.innocenceClaims,
    biasIndicators: analysis.biasIndicators,
    legalMemo,
  });

  const { label, color, description } = getScoreCategory(score);

  if (compact) {
    return (
      <div className="space-y-2">
        <div className="flex items-center justify-between">
          <span className="text-sm font-medium text-muted-foreground">Innocence Likelihood</span>
          <span className={`text-2xl font-bold ${color}`}>{score}</span>
        </div>
        <Progress value={score} className="h-2" />
        <p className="text-xs text-muted-foreground">{label}</p>
      </div>
    );
  }

  return (
    <Card className="p-6 border-border shadow-md bg-gradient-to-br from-background to-muted/20">
      <div className="flex items-start gap-4">
        <div className="p-3 rounded-lg bg-primary/10">
          <Scale className="w-8 h-8 text-primary" />
        </div>
        <div className="flex-1">
          <div className="flex items-center justify-between mb-2">
            <h3 className="text-xl font-bold text-foreground">
              Innocence Likelihood Score
            </h3>
            <Badge variant="outline" className="gap-1">
              <TrendingUp className="w-3 h-3" />
              AI Analysis
            </Badge>
          </div>
          
          <div className="flex items-end gap-4 mb-4">
            <div className={`text-6xl font-bold ${color}`}>{score}</div>
            <div className="pb-2">
              <p className={`text-lg font-semibold ${color}`}>{label}</p>
              <p className="text-sm text-muted-foreground">out of 100</p>
            </div>
          </div>

          <Progress value={score} className="h-3 mb-4" />
          
          <p className="text-sm text-muted-foreground mb-4">{description}</p>
          
          <div className="grid grid-cols-2 gap-3 text-xs">
            <div className="p-3 bg-muted/50 rounded-lg">
              <p className="text-muted-foreground mb-1">Innocence Claims</p>
              <p className="font-semibold text-foreground">
                {analysis.innocenceClaims?.count || 0} detected
              </p>
            </div>
            <div className="p-3 bg-muted/50 rounded-lg">
              <p className="text-muted-foreground mb-1">Bias Indicators</p>
              <p className="font-semibold text-foreground">
                {analysis.biasIndicators?.categories?.length || 0} categories
              </p>
            </div>
            <div className="p-3 bg-muted/50 rounded-lg">
              <p className="text-muted-foreground mb-1">Wrongful Conv. Issues</p>
              <p className="font-semibold text-foreground">
                {legalMemo?.wrongful_conviction_issues?.length || 0} identified
              </p>
            </div>
            <div className="p-3 bg-muted/50 rounded-lg">
              <p className="text-muted-foreground mb-1">Evidence Used</p>
              <p className="font-semibold text-foreground">
                {legalMemo?.evidence_used_to_convict?.length || 0} pieces
              </p>
            </div>
          </div>

          <div className="mt-4 p-3 bg-muted/30 rounded-lg border-l-4 border-primary">
            <p className="text-xs text-muted-foreground">
              <strong>Note:</strong> This score is generated by AI analysis and should be used as a screening tool only. 
              It does not constitute legal advice and requires human review and validation.
            </p>
          </div>
        </div>
      </div>
    </Card>
  );
};

export default InnocenceScoreCard;
